-- Notifications (user_id null = everyone)
create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id integer references users(id) on delete cascade,
  type text not null default 'info',
  title_en text not null, title_kh text, body_en text, body_kh text,
  link text, starts_at timestamptz, created_at timestamptz default now()
);

-- Sponsors slideshow, curated top places, site settings
create table if not exists sponsors (
  id bigint generated by default as identity primary key,
  title text not null, image_urls text, link_url text,
  starts_on date, ends_on date, is_active smallint not null default 1, sort_order int not null default 0
);
create table if not exists top_places (place_id integer primary key references places(id) on delete cascade, sort_order int not null default 0);
create table if not exists app_settings (key text primary key, value text);
