-- New festival => notification for everybody
create or replace function on_new_festival() returns trigger language plpgsql as $$
begin
  insert into notifications (type, title_en, title_kh, body_en, link, starts_at)
  values ('festival', 'New festival: ' || new.name_en, new.name_kh, new.when_en, '#festivals', now());
  return new;
end $$;
drop trigger if exists festival_notify on festivals;
create trigger festival_notify after insert on festivals for each row execute function on_new_festival();

-- Guide / transport application approved or rejected => notify that user
create or replace function on_application_status() returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status and new.user_id is not null then
    insert into notifications (user_id, type, title_en, title_kh, body_en)
    values (new.user_id, 'access',
      case new.status when 'approved' then 'Your application was approved' when 'rejected' then 'Your application was rejected' else 'Application status: ' || new.status end,
      case new.status when 'approved' then 'ពាក្យសុំរបស់អ្នកត្រូវបានអនុម័ត' when 'rejected' then 'ពាក្យសុំរបស់អ្នកត្រូវបានបដិសេធ' else null end,
      new.admin_notes);
  end if;
  return new;
end $$;
drop trigger if exists guide_status on guide_applications;
create trigger guide_status after update on guide_applications for each row execute function on_application_status();
drop trigger if exists transport_status on transport_applications;
create trigger transport_status after update on transport_applications for each row execute function on_application_status();
